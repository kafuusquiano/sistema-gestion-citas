-- =====================================================================
-- V4 - Modulo cita: el modulo central.
--
-- Cubre el objetivo especifico 2: eliminar conflictos de horario y
-- registrar inasistencias y reprogramaciones.
-- =====================================================================

CREATE TABLE citas (
    id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id      BIGINT      NOT NULL,
    medico_id        BIGINT      NOT NULL,

    fecha_hora       TIMESTAMPTZ NOT NULL,
    duracion_minutos SMALLINT    NOT NULL DEFAULT 20,

    estado           VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADA',
    tipo             VARCHAR(20) NOT NULL DEFAULT 'CONSULTA',

    motivo           VARCHAR(300),
    observaciones    VARCHAR(500),

    -- Quien cancelo y por que, para el reporte de cancelaciones.
    motivo_cancelacion VARCHAR(300),
    cancelada_por      BIGINT,

    -- Bloqueo optimista de @Version. Si dos personas tocan la misma cita a
    -- la vez, la segunda recibe OptimisticLockingFailureException y el
    -- GlobalExceptionHandler la traduce a 409.
    version          BIGINT      NOT NULL DEFAULT 0,

    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ,
    created_by       VARCHAR(64),
    updated_by       VARCHAR(64),

    CONSTRAINT fk_citas_paciente FOREIGN KEY (paciente_id)
        REFERENCES pacientes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_citas_medico FOREIGN KEY (medico_id)
        REFERENCES medicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_citas_cancelada_por FOREIGN KEY (cancelada_por)
        REFERENCES usuarios (id) ON DELETE SET NULL,

    CONSTRAINT ck_citas_estado CHECK (estado IN
        ('PROGRAMADA', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA', 'REPROGRAMADA', 'NO_ASISTIO')),

    CONSTRAINT ck_citas_tipo CHECK (tipo IN ('CONSULTA', 'CONTROL', 'EMERGENCIA')),

    CONSTRAINT ck_citas_duracion CHECK (duracion_minutos BETWEEN 10 AND 120),

    -- Si esta cancelada, debe constar el motivo.
    CONSTRAINT ck_citas_motivo_cancelacion CHECK (
        estado <> 'CANCELADA' OR motivo_cancelacion IS NOT NULL)
);

COMMENT ON TABLE citas IS 'Citas medicas. El indice uk_citas_medico_slot impide la doble reserva a nivel de base de datos.';

-- ---------------------------------------------------------------------
-- La regla que impide la doble reserva.
--
-- Es un indice PARCIAL, no un unique comun. Solo ocupan el turno las
-- citas vigentes: PROGRAMADA y CONFIRMADA. Una cita CANCELADA, COMPLETADA,
-- NO_ASISTIO o REPROGRAMADA deja el turno libre para otro paciente.
--
-- Con un UNIQUE sobre (medico_id, fecha_hora) sin filtro, cancelar una
-- cita bloquearia ese horario para siempre, que es justo lo contrario de
-- lo que necesita el establecimiento.
-- ---------------------------------------------------------------------
CREATE UNIQUE INDEX uk_citas_medico_slot ON citas (medico_id, fecha_hora)
    WHERE estado IN ('PROGRAMADA', 'CONFIRMADA');

-- Agenda del dia de un medico y pantalla "mis citas" del paciente.
CREATE INDEX idx_citas_medico_fecha   ON citas (medico_id, fecha_hora);
CREATE INDEX idx_citas_paciente_fecha ON citas (paciente_id, fecha_hora DESC);
CREATE INDEX idx_citas_estado         ON citas (estado);

-- Lo que recorre el scheduler que marca inasistencias: solo las vigentes
-- ya pasadas, no la tabla completa.
CREATE INDEX idx_citas_pendientes ON citas (fecha_hora)
    WHERE estado IN ('PROGRAMADA', 'CONFIRMADA');


-- ---------------------------------------------------------------------
-- citas_historial_estado: traza de cada cambio.
--
-- Da la trazabilidad de reprogramaciones e inasistencias que pide el
-- objetivo 2. Guarda tambien la fecha anterior, porque al reprogramar se
-- actualiza fecha_hora en la misma fila y sin esto se perderia el dato.
-- ---------------------------------------------------------------------
CREATE TABLE citas_historial_estado (
    id                    BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id               BIGINT      NOT NULL,

    estado_anterior       VARCHAR(20),
    estado_nuevo          VARCHAR(20) NOT NULL,

    -- Solo se llenan en una reprogramacion.
    fecha_hora_anterior   TIMESTAMPTZ,
    fecha_hora_nueva      TIMESTAMPTZ,

    motivo                VARCHAR(300),

    -- Nulo si el cambio lo hizo un proceso automatico, como el scheduler
    -- que marca NO_ASISTIO.
    usuario_id            BIGINT,

    created_at            TIMESTAMPTZ NOT NULL,
    updated_at            TIMESTAMPTZ,
    created_by            VARCHAR(64),
    updated_by            VARCHAR(64),

    CONSTRAINT fk_historial_cita FOREIGN KEY (cita_id)
        REFERENCES citas (id) ON DELETE CASCADE,
    CONSTRAINT fk_historial_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON DELETE SET NULL,

    CONSTRAINT ck_historial_estado_nuevo CHECK (estado_nuevo IN
        ('PROGRAMADA', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA', 'REPROGRAMADA', 'NO_ASISTIO'))
);

CREATE INDEX idx_historial_cita ON citas_historial_estado (cita_id, created_at DESC);
