-- =====================================================================
-- V2 - Modulo paciente: ficha del paciente y contacto de emergencia.
-- =====================================================================

-- ---------------------------------------------------------------------
-- pacientes
--
-- usuario_id es opcional a proposito. Admision registra pacientes que
-- llegan por ventanilla y no tienen cuenta en el sistema; la cuenta se
-- vincula despues si el paciente quiere agendar en linea. Por eso el DNI
-- y los nombres viven tambien aqui y no solo en usuarios.
-- ---------------------------------------------------------------------
CREATE TABLE pacientes (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Cuenta de acceso, si el paciente la tiene.
    usuario_id        BIGINT,

    -- Numero de historia clinica del establecimiento.
    numero_historia   VARCHAR(20)  NOT NULL,

    tipo_documento    VARCHAR(20)  NOT NULL DEFAULT 'DNI',
    numero_documento  VARCHAR(12)  NOT NULL,

    -- Apellidos separados, como los maneja el RENIEC.
    nombres           VARCHAR(100) NOT NULL,
    apellido_paterno  VARCHAR(60)  NOT NULL,
    apellido_materno  VARCHAR(60),

    fecha_nacimiento  DATE         NOT NULL,
    sexo              VARCHAR(10)  NOT NULL,
    grupo_sanguineo   VARCHAR(5),

    telefono          VARCHAR(20),
    email             VARCHAR(150),
    direccion         VARCHAR(200),
    distrito          VARCHAR(80),

    -- Tipo de seguro, necesario para los reportes de produccion.
    seguro            VARCHAR(20)  NOT NULL DEFAULT 'SIS',

    estado            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',

    created_at        TIMESTAMPTZ  NOT NULL,
    updated_at        TIMESTAMPTZ,
    created_by        VARCHAR(64),
    updated_by        VARCHAR(64),

    CONSTRAINT uk_pacientes_numero_historia UNIQUE (numero_historia),
    CONSTRAINT uk_pacientes_documento       UNIQUE (tipo_documento, numero_documento),

    -- Una cuenta de usuario no puede pertenecer a dos pacientes.
    CONSTRAINT uk_pacientes_usuario         UNIQUE (usuario_id),

    CONSTRAINT fk_pacientes_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON DELETE SET NULL,

    CONSTRAINT ck_pacientes_tipo_doc CHECK (tipo_documento IN ('DNI', 'CARNE_EXTRANJERIA', 'PASAPORTE')),
    CONSTRAINT ck_pacientes_sexo     CHECK (sexo IN ('MASCULINO', 'FEMENINO')),
    CONSTRAINT ck_pacientes_seguro   CHECK (seguro IN ('SIS', 'ESSALUD', 'PRIVADO', 'NINGUNO')),
    CONSTRAINT ck_pacientes_estado   CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_pacientes_grupo    CHECK (grupo_sanguineo IS NULL OR grupo_sanguineo IN
        ('O+', 'O-', 'A+', 'A-', 'B+', 'B-', 'AB+', 'AB-')),

    -- Un DNI son 8 digitos; los otros documentos admiten mas.
    CONSTRAINT ck_pacientes_dni CHECK (
        tipo_documento <> 'DNI' OR numero_documento ~ '^[0-9]{8}$'),

    -- Sin fechas de nacimiento futuras, que es el error tipico de tipeo.
    CONSTRAINT ck_pacientes_fecha_nac CHECK (fecha_nacimiento <= CURRENT_DATE)
);

COMMENT ON TABLE  pacientes            IS 'Ficha del paciente. usuario_id es nulo para quienes se registran por ventanilla sin cuenta.';
COMMENT ON COLUMN pacientes.numero_historia IS 'Numero de historia clinica del Centro de Salud Acapulco.';

CREATE INDEX idx_pacientes_documento ON pacientes (numero_documento);
CREATE INDEX idx_pacientes_estado    ON pacientes (estado);

-- Busqueda por nombre con ILIKE '%texto%'. El indice GIN con trigramas es
-- lo que permite que esa consulta no recorra la tabla entera.
CREATE INDEX idx_pacientes_nombres_trgm ON pacientes
    USING GIN ((nombres || ' ' || apellido_paterno || ' ' || COALESCE(apellido_materno, '')) gin_trgm_ops);


-- ---------------------------------------------------------------------
-- contactos_emergencia: a quien avisar. Varios por paciente.
-- ---------------------------------------------------------------------
CREATE TABLE contactos_emergencia (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id  BIGINT       NOT NULL,
    nombres      VARCHAR(150) NOT NULL,
    parentesco   VARCHAR(40)  NOT NULL,
    telefono     VARCHAR(20)  NOT NULL,
    es_principal BOOLEAN      NOT NULL DEFAULT FALSE,

    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ,
    created_by   VARCHAR(64),
    updated_by   VARCHAR(64),

    CONSTRAINT fk_contactos_paciente FOREIGN KEY (paciente_id)
        REFERENCES pacientes (id) ON DELETE CASCADE
);

CREATE INDEX idx_contactos_paciente ON contactos_emergencia (paciente_id);

-- Un solo contacto principal por paciente.
CREATE UNIQUE INDEX uk_contactos_principal ON contactos_emergencia (paciente_id)
    WHERE es_principal = TRUE;
