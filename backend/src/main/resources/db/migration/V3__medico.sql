-- =====================================================================
-- V3 - Modulo medico: especialidades, medicos, horarios y excepciones.
--
-- Aqui se materializa la herencia que exige la seccion 1.3.1 del
-- proyecto: Medico es la clase base, MedicoGeneral y MedicoEspecialista
-- la extienden. Se mapea con @Inheritance(SINGLE_TABLE), asi que ambas
-- subclases comparten la tabla medicos y se distinguen por la columna
-- discriminadora tipo_medico.
-- =====================================================================

-- ---------------------------------------------------------------------
-- especialidades: obstetricia, enfermeria, odontologia, medicina general
-- y las demas del alcance del proyecto.
-- ---------------------------------------------------------------------
CREATE TABLE especialidades (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,

    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(64),
    updated_by  VARCHAR(64),

    CONSTRAINT uk_especialidades_nombre UNIQUE (nombre)
);


-- ---------------------------------------------------------------------
-- medicos (tabla unica de la jerarquia)
--
-- tipo_medico es el discriminador. Las columnas propias de una sola
-- subclase son NOT NULL por CHECK condicional, no por NOT NULL de
-- columna: en SINGLE_TABLE la columna existe para ambas subclases y la
-- otra la deja en nulo.
-- ---------------------------------------------------------------------
CREATE TABLE medicos (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Columna discriminadora de la herencia.
    tipo_medico      VARCHAR(20)  NOT NULL,

    usuario_id       BIGINT       NOT NULL,

    -- Colegio Medico del Peru. Todo medico colegiado tiene uno.
    cmp              VARCHAR(10)  NOT NULL,

    nombres          VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(60)  NOT NULL,
    apellido_materno VARCHAR(60),
    telefono         VARCHAR(20),

    especialidad_id  BIGINT       NOT NULL,

    -- --- Solo MedicoEspecialista ---
    -- Registro Nacional de Especialista, que el medico general no tiene.
    rne              VARCHAR(10),
    anios_experiencia SMALLINT,

    -- --- Solo MedicoGeneral ---
    -- Area en la que rota dentro del establecimiento.
    area_rotacion    VARCHAR(80),

    estado           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',

    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ,
    created_by       VARCHAR(64),
    updated_by       VARCHAR(64),

    CONSTRAINT uk_medicos_cmp     UNIQUE (cmp),
    CONSTRAINT uk_medicos_usuario UNIQUE (usuario_id),
    CONSTRAINT uk_medicos_rne     UNIQUE (rne),

    CONSTRAINT fk_medicos_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_medicos_especialidad FOREIGN KEY (especialidad_id)
        REFERENCES especialidades (id) ON DELETE RESTRICT,

    CONSTRAINT ck_medicos_tipo   CHECK (tipo_medico IN ('GENERAL', 'ESPECIALISTA')),
    CONSTRAINT ck_medicos_estado CHECK (estado IN ('ACTIVO', 'INACTIVO', 'LICENCIA')),
    CONSTRAINT ck_medicos_cmp    CHECK (cmp ~ '^[0-9]{1,6}$'),

    -- Un especialista tiene RNE; un medico general no.
    CONSTRAINT ck_medicos_rne_por_tipo CHECK (
        (tipo_medico = 'ESPECIALISTA' AND rne IS NOT NULL)
     OR (tipo_medico = 'GENERAL'      AND rne IS NULL)),

    CONSTRAINT ck_medicos_experiencia CHECK (
        anios_experiencia IS NULL OR anios_experiencia BETWEEN 0 AND 70)
);

COMMENT ON TABLE  medicos            IS 'Jerarquia Medico con estrategia SINGLE_TABLE. tipo_medico discrimina MedicoGeneral de MedicoEspecialista.';
COMMENT ON COLUMN medicos.tipo_medico IS 'Columna discriminadora de @Inheritance(SINGLE_TABLE).';
COMMENT ON COLUMN medicos.rne        IS 'Registro Nacional de Especialista. Obligatorio solo para ESPECIALISTA.';

CREATE INDEX idx_medicos_especialidad ON medicos (especialidad_id);
CREATE INDEX idx_medicos_tipo         ON medicos (tipo_medico);
CREATE INDEX idx_medicos_estado       ON medicos (estado);


-- ---------------------------------------------------------------------
-- horarios: plantilla semanal de atencion de cada medico.
--
-- duracion_slot_minutos es lo que divide la franja en turnos: una franja
-- de 08:00 a 12:00 con slots de 20 minutos da 12 turnos.
-- ---------------------------------------------------------------------
CREATE TABLE horarios (
    id                    BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id             BIGINT      NOT NULL,
    dia_semana            VARCHAR(10) NOT NULL,
    hora_inicio           TIME        NOT NULL,
    hora_fin              TIME        NOT NULL,
    duracion_slot_minutos SMALLINT    NOT NULL DEFAULT 20,
    activo                BOOLEAN     NOT NULL DEFAULT TRUE,

    created_at            TIMESTAMPTZ NOT NULL,
    updated_at            TIMESTAMPTZ,
    created_by            VARCHAR(64),
    updated_by            VARCHAR(64),

    CONSTRAINT fk_horarios_medico FOREIGN KEY (medico_id)
        REFERENCES medicos (id) ON DELETE CASCADE,

    CONSTRAINT ck_horarios_dia CHECK (dia_semana IN
        ('LUNES', 'MARTES', 'MIERCOLES', 'JUEVES', 'VIERNES', 'SABADO', 'DOMINGO')),

    -- Sin franjas invertidas ni de duracion cero.
    CONSTRAINT ck_horarios_rango CHECK (hora_fin > hora_inicio),

    CONSTRAINT ck_horarios_slot CHECK (duracion_slot_minutos IN (10, 15, 20, 30, 45, 60))
);

CREATE INDEX idx_horarios_medico     ON horarios (medico_id);
CREATE INDEX idx_horarios_medico_dia ON horarios (medico_id, dia_semana) WHERE activo = TRUE;


-- ---------------------------------------------------------------------
-- excepciones_horario: vacaciones, feriados y licencias.
--
-- Al calcular la disponibilidad, estas fechas se restan de la plantilla
-- semanal. Es lo que evita agendar una cita un dia que el medico no esta.
-- ---------------------------------------------------------------------
CREATE TABLE excepciones_horario (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Nulo significa que aplica a todo el establecimiento, como un feriado.
    medico_id    BIGINT,

    fecha_inicio DATE         NOT NULL,
    fecha_fin    DATE         NOT NULL,
    motivo       VARCHAR(20)  NOT NULL,
    descripcion  VARCHAR(200),

    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ,
    created_by   VARCHAR(64),
    updated_by   VARCHAR(64),

    CONSTRAINT fk_excepciones_medico FOREIGN KEY (medico_id)
        REFERENCES medicos (id) ON DELETE CASCADE,

    CONSTRAINT ck_excepciones_motivo CHECK (motivo IN
        ('VACACIONES', 'FERIADO', 'LICENCIA', 'CAPACITACION', 'OTRO')),

    CONSTRAINT ck_excepciones_rango CHECK (fecha_fin >= fecha_inicio)
);

COMMENT ON COLUMN excepciones_horario.medico_id IS 'Nulo cuando la excepcion aplica a todo el establecimiento, por ejemplo un feriado.';

CREATE INDEX idx_excepciones_medico ON excepciones_horario (medico_id);
CREATE INDEX idx_excepciones_fechas ON excepciones_horario (fecha_inicio, fecha_fin);
