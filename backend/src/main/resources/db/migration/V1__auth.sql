-- Busqueda de pacientes por nombre con ILIKE '%texto%' sin escaneo completo.
-- Sirve al objetivo especifico 1: reducir el tiempo de busqueda en admision.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Busqueda insensible a tildes: "nunez" encuentra "Nuñez".
CREATE EXTENSION IF NOT EXISTS unaccent;


-- ---------------------------------------------------------------------
-- usuarios: credenciales y rol. Los datos personales viven en pacientes
-- y en medicos, no aqui.
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(150) NOT NULL,
    dni             VARCHAR(8)   NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    rol             VARCHAR(20)  NOT NULL,
    estado          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',

    -- Para bloquear la cuenta tras varios intentos fallidos de login.
    intentos_fallidos SMALLINT   NOT NULL DEFAULT 0,
    ultimo_acceso     TIMESTAMPTZ,

    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ,
    created_by      VARCHAR(64),
    updated_by      VARCHAR(64),

    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT uk_usuarios_dni   UNIQUE (dni),

    -- Los enums se guardan como texto con CHECK en vez de usar un tipo
    -- ENUM de PostgreSQL: agregar un valor a un ENUM exige ALTER TYPE,
    -- que no corre dentro de una transaccion de Flyway.
    CONSTRAINT ck_usuarios_rol    CHECK (rol IN ('ADMIN', 'MEDICO', 'PACIENTE')),
    CONSTRAINT ck_usuarios_estado CHECK (estado IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO')),
    CONSTRAINT ck_usuarios_dni    CHECK (dni ~ '^[0-9]{8}$')
);

COMMENT ON TABLE  usuarios     IS 'Credenciales de acceso y rol. Los datos personales estan en pacientes y medicos.';
COMMENT ON COLUMN usuarios.dni IS 'DNI de 8 digitos del RENIEC. Sirve tambien como identificador de login alternativo.';

CREATE INDEX idx_usuarios_rol    ON usuarios (rol);
CREATE INDEX idx_usuarios_estado ON usuarios (estado);


-- ---------------------------------------------------------------------
-- refresh_tokens: un registro por sesion abierta.
--
-- Se guardan en PostgreSQL y no solo en Redis porque en dev no hay Redis
-- y porque la sesion debe sobrevivir a un reinicio del backend, algo que
-- en Render pasa cada vez que el servicio despierta.
-- ---------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL,

    -- jti del token. No se guarda el token completo: con el jti basta para
    -- revocarlo, y asi una filtracion de esta tabla no entrega sesiones.
    jti         VARCHAR(64) NOT NULL,

    expira_en   TIMESTAMPTZ NOT NULL,
    revocado    BOOLEAN     NOT NULL DEFAULT FALSE,
    revocado_en TIMESTAMPTZ,

    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(64),
    updated_by  VARCHAR(64),

    CONSTRAINT uk_refresh_tokens_jti UNIQUE (jti),
    CONSTRAINT fk_refresh_tokens_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_tokens_usuario ON refresh_tokens (usuario_id);

-- Para el barrido periodico de tokens vencidos.
CREATE INDEX idx_refresh_tokens_expira ON refresh_tokens (expira_en)
    WHERE revocado = FALSE;
