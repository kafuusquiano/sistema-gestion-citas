-- =====================================================================
-- V5 - Modulo notificacion: correo y avisos dentro de la aplicacion.
-- =====================================================================

CREATE TABLE notificaciones (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    destinatario_id BIGINT       NOT NULL,

    tipo            VARCHAR(30)  NOT NULL,
    canal           VARCHAR(10)  NOT NULL,
    estado          VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',

    asunto          VARCHAR(200) NOT NULL,
    mensaje         TEXT         NOT NULL,

    -- A que apunta la notificacion, para que el frontend sepa a donde
    -- navegar al tocarla. No es una FK porque puede referir a una cita,
    -- a un resultado de laboratorio o a nada.
    referencia_tipo VARCHAR(30),
    referencia_id   BIGINT,

    enviado_en      TIMESTAMPTZ,
    leido_en        TIMESTAMPTZ,

    -- Reintentos del envio por correo y el ultimo error, para diagnosticar
    -- sin tener que revisar los logs del servidor.
    intentos        SMALLINT     NOT NULL DEFAULT 0,
    ultimo_error    VARCHAR(500),

    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ,
    created_by      VARCHAR(64),
    updated_by      VARCHAR(64),

    CONSTRAINT fk_notificaciones_destinatario FOREIGN KEY (destinatario_id)
        REFERENCES usuarios (id) ON DELETE CASCADE,

    CONSTRAINT ck_notificaciones_tipo CHECK (tipo IN (
        'BIENVENIDA',
        'CITA_CONFIRMADA',
        'CITA_CANCELADA',
        'CITA_REPROGRAMADA',
        'RECORDATORIO',
        'RESULTADO_DISPONIBLE',
        'VALOR_CRITICO')),

    CONSTRAINT ck_notificaciones_canal CHECK (canal IN ('EMAIL', 'IN_APP')),

    CONSTRAINT ck_notificaciones_estado CHECK (estado IN
        ('PENDIENTE', 'ENVIADA', 'FALLIDA', 'LEIDA')),

    -- Una notificacion enviada tiene que tener su fecha de envio.
    CONSTRAINT ck_notificaciones_enviado CHECK (
        estado NOT IN ('ENVIADA', 'LEIDA') OR enviado_en IS NOT NULL)
);

COMMENT ON COLUMN notificaciones.referencia_tipo IS 'CITA o RESULTADO. Junto con referencia_id dice a donde navegar desde el panel.';

-- La campana de notificaciones: no leidas del usuario, mas recientes primero.
CREATE INDEX idx_notificaciones_destinatario ON notificaciones (destinatario_id, created_at DESC);

CREATE INDEX idx_notificaciones_no_leidas ON notificaciones (destinatario_id)
    WHERE estado <> 'LEIDA';

-- Lo que recorre el reintento de envios fallidos.
CREATE INDEX idx_notificaciones_pendientes ON notificaciones (created_at)
    WHERE estado IN ('PENDIENTE', 'FALLIDA');
