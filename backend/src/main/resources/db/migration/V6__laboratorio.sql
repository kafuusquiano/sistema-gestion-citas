-- =====================================================================
-- V6 - Modulo laboratorio: catalogo, rangos de referencia y ordenes.
--
-- Los resultados en si no estan aqui: viven en MongoDB, porque cada
-- examen tiene una forma distinta (instruccion M3). Esta migracion cubre
-- lo estructurado: que se puede pedir, con que valores se compara y
-- que ordenes existen.
-- =====================================================================

-- ---------------------------------------------------------------------
-- examenes_catalogo: hemograma, glucosa, perfil lipidico y demas.
-- ---------------------------------------------------------------------
CREATE TABLE examenes_catalogo (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Codigo interno del laboratorio del establecimiento.
    codigo      VARCHAR(20)  NOT NULL,
    nombre      VARCHAR(150) NOT NULL,
    categoria   VARCHAR(50)  NOT NULL,

    -- Unidad en que se informa: mg/dL, g/dL, celulas/uL.
    unidad      VARCHAR(20),
    metodo      VARCHAR(100),

    -- Horas estimadas hasta tener el resultado.
    tiempo_proceso_horas SMALLINT,

    requiere_ayuno BOOLEAN   NOT NULL DEFAULT FALSE,
    activo         BOOLEAN   NOT NULL DEFAULT TRUE,

    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ,
    created_by  VARCHAR(64),
    updated_by  VARCHAR(64),

    CONSTRAINT uk_examenes_codigo UNIQUE (codigo),

    CONSTRAINT ck_examenes_categoria CHECK (categoria IN
        ('HEMATOLOGIA', 'BIOQUIMICA', 'MICROBIOLOGIA', 'INMUNOLOGIA', 'UROANALISIS', 'OTRO'))
);

CREATE INDEX idx_examenes_categoria ON examenes_catalogo (categoria) WHERE activo = TRUE;


-- ---------------------------------------------------------------------
-- rangos_referencia: con que valores se compara un resultado.
--
-- Hay varias filas por examen porque el rango normal depende del sexo y
-- de la edad: la hemoglobina normal de un nino no es la de un adulto.
-- RangoReferenciaEvaluator elige la fila que corresponde al paciente y
-- clasifica el resultado en NORMAL, ALTO, BAJO o CRITICO.
-- ---------------------------------------------------------------------
CREATE TABLE rangos_referencia (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examen_id    BIGINT       NOT NULL,

    -- Nulo significa que el rango aplica a ambos sexos.
    sexo         VARCHAR(10),

    edad_min_anios SMALLINT   NOT NULL DEFAULT 0,
    edad_max_anios SMALLINT   NOT NULL DEFAULT 120,

    valor_min    NUMERIC(12, 4),
    valor_max    NUMERIC(12, 4),

    -- Fuera de estos limites el valor es critico y dispara el evento
    -- laboratorio.valor-critico, que notifica al medico de inmediato.
    critico_min  NUMERIC(12, 4),
    critico_max  NUMERIC(12, 4),

    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ,
    created_by   VARCHAR(64),
    updated_by   VARCHAR(64),

    CONSTRAINT fk_rangos_examen FOREIGN KEY (examen_id)
        REFERENCES examenes_catalogo (id) ON DELETE CASCADE,

    CONSTRAINT ck_rangos_sexo CHECK (sexo IS NULL OR sexo IN ('MASCULINO', 'FEMENINO')),

    CONSTRAINT ck_rangos_edad CHECK (edad_max_anios >= edad_min_anios),

    CONSTRAINT ck_rangos_valores CHECK (
        valor_min IS NULL OR valor_max IS NULL OR valor_max >= valor_min)
);

COMMENT ON COLUMN rangos_referencia.sexo IS 'Nulo cuando el rango aplica a ambos sexos.';

CREATE INDEX idx_rangos_examen ON rangos_referencia (examen_id);


-- ---------------------------------------------------------------------
-- ordenes_laboratorio: la peticion que firma el medico.
-- ---------------------------------------------------------------------
CREATE TABLE ordenes_laboratorio (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    numero_orden  VARCHAR(20)  NOT NULL,

    paciente_id   BIGINT       NOT NULL,
    medico_id     BIGINT       NOT NULL,

    -- Cita en la que se pidio, si fue durante una consulta.
    cita_id       BIGINT,

    estado        VARCHAR(20)  NOT NULL DEFAULT 'SOLICITADA',
    prioridad     VARCHAR(20)  NOT NULL DEFAULT 'NORMAL',

    diagnostico_presuntivo VARCHAR(300),
    observaciones VARCHAR(500),

    fecha_toma_muestra TIMESTAMPTZ,
    fecha_validacion   TIMESTAMPTZ,

    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ,
    created_by    VARCHAR(64),
    updated_by    VARCHAR(64),

    CONSTRAINT uk_ordenes_numero UNIQUE (numero_orden),

    CONSTRAINT fk_ordenes_paciente FOREIGN KEY (paciente_id)
        REFERENCES pacientes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ordenes_medico FOREIGN KEY (medico_id)
        REFERENCES medicos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ordenes_cita FOREIGN KEY (cita_id)
        REFERENCES citas (id) ON DELETE SET NULL,

    CONSTRAINT ck_ordenes_estado CHECK (estado IN
        ('SOLICITADA', 'MUESTRA_TOMADA', 'EN_PROCESO', 'VALIDADA', 'ANULADA')),

    CONSTRAINT ck_ordenes_prioridad CHECK (prioridad IN ('NORMAL', 'URGENTE'))
);

CREATE INDEX idx_ordenes_paciente ON ordenes_laboratorio (paciente_id, created_at DESC);
CREATE INDEX idx_ordenes_medico   ON ordenes_laboratorio (medico_id);
CREATE INDEX idx_ordenes_estado   ON ordenes_laboratorio (estado);

-- Bandeja del laboratorio: lo que esta por procesar, urgentes primero.
CREATE INDEX idx_ordenes_bandeja ON ordenes_laboratorio (prioridad DESC, created_at)
    WHERE estado IN ('SOLICITADA', 'MUESTRA_TOMADA', 'EN_PROCESO');


-- ---------------------------------------------------------------------
-- ordenes_examenes: que examenes incluye cada orden.
--
-- Tabla intermedia con estado propio, porque una orden puede tener un
-- examen validado y otro todavia en proceso.
-- ---------------------------------------------------------------------
CREATE TABLE ordenes_examenes (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id   BIGINT       NOT NULL,
    examen_id  BIGINT       NOT NULL,

    estado     VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',

    -- Id del documento de MongoDB con el resultado. No es una FK: apunta
    -- a otra base de datos.
    resultado_documento_id VARCHAR(50),

    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),

    CONSTRAINT uk_ordenes_examenes UNIQUE (orden_id, examen_id),

    CONSTRAINT fk_ordenes_examenes_orden FOREIGN KEY (orden_id)
        REFERENCES ordenes_laboratorio (id) ON DELETE CASCADE,
    CONSTRAINT fk_ordenes_examenes_examen FOREIGN KEY (examen_id)
        REFERENCES examenes_catalogo (id) ON DELETE RESTRICT,

    CONSTRAINT ck_ordenes_examenes_estado CHECK (estado IN
        ('PENDIENTE', 'EN_PROCESO', 'VALIDADO', 'ANULADO'))
);

COMMENT ON COLUMN ordenes_examenes.resultado_documento_id IS 'Id del documento en MongoDB con el resultado. No es FK: es otra base de datos.';

CREATE INDEX idx_ordenes_examenes_orden ON ordenes_examenes (orden_id);
